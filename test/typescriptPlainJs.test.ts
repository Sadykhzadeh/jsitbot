describe("plain JavaScript is not changed by the TypeScript path", () => {
  const sandbox = new QuickJsSandboxService();

  test("each snippet has the same answer as the JavaScript path", async () => {
    expect(CORPUS.length).toBeGreaterThanOrEqual(100);
    for (const [code, expected] of CORPUS) {
      const execution = await sandbox.execute(code);
      const answer = execution.ok ? execution.result : `error: ${execution.error}`;

      expect({ code, answer }).toEqual({ code, answer: expected });
    }
    // The table runs 115 programs one after another. On a busy machine that
    // takes between 2.5 and 6 s on either Bun version, so it needs more time
    // than the default five seconds.
  }, 60_000);
});
